#!/usr/bin/env node
/*
 * Generates the narrator + Penelope lines with neural TTS (edge-tts via uvx),
 * measures each clip, resolves overlaps, and writes ../narration.js so the
 * picture (inscriptions) and the mix share one timing source.
 *
 *   node tools/make-narration.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const CLIP_DIR = path.join(ROOT, 'narration');

const NARRATOR = { voice: 'en-US-ChristopherNeural', rate: '-6%', pitch: '-6Hz' };
const PENELOPE = { voice: 'en-GB-SoniaNeural', rate: '-30%', pitch: '-2Hz' };

// Lines play in order; `pause` is the breathing room (seconds) before a line,
// where the picture carries the story alone. The first line starts at FIRST_LINE_AT.
const FIRST_LINE_AT = 10.6;
const LINES = [
  { id: 'legend', pause: 0, text: 'Legend tells of a king who sailed for ten years…' },
  { id: 'untouched', pause: 0.5, text: '…and never once touched his work.' },
  { id: 'desk', pause: 1.6, text: 'He left it at home, on a desk beneath an olive tree,' },
  { id: 'thread', pause: 0.5, text: 'and tied it to his hand with a single red thread.' },
  { id: 'sea', pause: 2.6, text: 'The sea did everything it could… to make him stop.' },
  { id: 'lotus', pause: 2.2, text: 'The lotus-eaters offered him forgetting. He accepted.' },
  { id: 'cave', pause: 2.2, text: "In the giant's cave there was no signal. He wrote one line, and it waited for the sun." },
  { id: 'circe', pause: 2.0, text: 'The enchantress asked permission. He gave it without putting down his cup.' },
  { id: 'sirens', pause: 2.0, text: 'The sirens sang the oldest song of all.' },
  { id: 'muted', pause: 3.0, text: 'He had muted them.' },
  { id: 'shapes', pause: 2.2, text: 'The shape-shifter wore four faces. It was always the same session.' },
  { id: 'dragon', pause: 2.6, text: 'Then came the dragon of the storm…' },
  { id: 'broke', pause: 1.8, text: '…and the thread broke.' },
  { id: 'switch', pause: 3.4, text: 'At home, his son reached for the switch.' },
  { id: 'wait', pause: 0.5, text: 'Wait.', speaker: 'penelope' },
  { id: 'remembered', pause: 1.2, text: 'But the thread remembered everything.' },
  { id: 'arrow', pause: 2.4, text: 'The king came home a beggar. In his own hall, he loosed a single arrow…' },
  { id: 'rings', pause: 2.0, text: '…through twelve rings. Twelve works. All done.' },
  { id: 'word', pause: 2.6, text: 'From the edge of the world, he sent one word home.' },
  { id: 'goes-on', pause: 4.2, text: 'The work goes on.' },
  { id: 'so-can-you', pause: 0.9, text: 'So can you.' },
];

function synthesize(line, file) {
  const voice = line.speaker === 'penelope' ? PENELOPE : NARRATOR;
  execFileSync('uvx', [
    'edge-tts', '--voice', voice.voice, `--rate=${voice.rate}`, `--pitch=${voice.pitch}`,
    '--text', line.text, '--write-media', file,
  ], { stdio: ['ignore', 'ignore', 'inherit'] });
}

function measure(file) {
  const output = execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file]);
  return Number(String(output).trim());
}

mkdirSync(CLIP_DIR, { recursive: true });
let cursor = FIRST_LINE_AT;
const scheduled = LINES.map((line, index) => {
  const file = path.join(CLIP_DIR, `${line.id}.mp3`);
  synthesize(line, file);
  const duration = measure(file);
  const start = index === 0 ? FIRST_LINE_AT : cursor + line.pause;
  cursor = start + duration;
  const entry = { id: line.id, speaker: line.speaker ?? 'narrator', text: line.text, start: Number(start.toFixed(3)), duration: Number(duration.toFixed(3)), file: `narration/${line.id}.mp3` };
  console.log(`${entry.id.padEnd(12)} start ${entry.start.toFixed(2)}  dur ${entry.duration.toFixed(2)}  end ${(entry.start + entry.duration).toFixed(2)}`);
  return entry;
});

const banner = '/* Generated by tools/make-narration.mjs — do not edit by hand. */\n';
writeFileSync(path.join(ROOT, 'narration.js'), `${banner}window.LEGEND_NARRATION = ${JSON.stringify(scheduled, null, 2)};\n`);
console.log('wrote narration.js');
